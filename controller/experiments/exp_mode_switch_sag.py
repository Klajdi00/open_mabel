def _set_fix(on):
    """Toggle the unified always-on gravity layer for before/after runs.

    The flag is read at import time at BOTH sites -- the torque engine (does it
    keep feeding the joints its law does not own?) and the gateway plant (does it
    transmit the feed-forward outside a torque mode?) -- so both modules, and
    everything that re-exports from them, are reloaded."""
    import importlib
    os.environ[FLAG] = "1" if on else "0"
    import mabel.whole_body_controller.engine as _e
    importlib.reload(_e)
    import mabel.facade as _f
    importlib.reload(_f)
    import mabel as _m
    importlib.reload(_m)
    import plant as _p
    importlib.reload(_p)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rig", choices=["inproc", "split", "both"], default="both")
    ap.add_argument("--quick", action="store_true", help="E1/E2 only, no figures")
    ap.add_argument("--out", default=FIGDIR)
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)

    rigs = ["inproc", "split"] if args.rig == "both" else [args.rig]
    summary = {}
    for key in rigs:
        cls = RIGS[key]
        print("\n" + "=" * 78)
        print(f"DEPLOYMENT: {cls.name}")
        print("=" * 78)

        phases = {}
        for on in (False, True):
            _set_fix(on)
            tag = "after" if on else "before"
            print(f"\n---------- {tag.upper()}  ({FLAG}={os.environ[FLAG]}) ----------")
            rows, tot, inv = e1_coverage(cls)
            e2 = e2_switch(cls)
            ph = {"coverage": tot, "invariant": inv, "e2": e2}
            if not args.quick:
                ph["e3"] = e3_stiffness(cls)
                ph["e4"] = e4_ratchet(cls)
                ph["trace"] = run_switch(cls, "joint", "impedance", "arm",
                                         trace=True)["trace"]
            phases[tag] = ph

        if not args.quick:
            fig_e2(phases["before"]["e2"], phases["after"]["e2"], cls.name,
                   os.path.join(args.out, f"modeswitch_e2_{key}.pdf"))
            fig_e3(phases["before"]["e3"], phases["after"]["e3"], cls.name,
                   os.path.join(args.out, f"modeswitch_e3_{key}.pdf"))
            fig_e4(phases["before"]["e4"], phases["after"]["e4"], cls.name,
                   os.path.join(args.out, f"modeswitch_e4_{key}.pdf"))
            fig_e5({t: phases[t]["trace"] for t in phases}, cls.name,
                   os.path.join(args.out, f"modeswitch_e5_{key}.pdf"))
        summary[key] = {
            t: {"coverage": p["coverage"], "invariant": p["invariant"],
                "e2": {k: {"groups": v["groups"], "worst": v["worst"],
                           "worst_joint": v["worst_joint"],
                           "palm_mm": v["palm_mm"], "back": v["back"]}
                      for k, v in p["e2"].items()}}
            for t, p in phases.items()}

    print("\n" + "=" * 78)
    print("VERDICT")
    print("=" * 78)
    for key, s in summary.items():
        cls = RIGS[key]
        b, a = s["before"], s["after"]
        wb = max(v["worst"] for v in b["e2"].values())
        wa = max(v["worst"] for v in a["e2"].values())
        print(f"{cls.name:26s}  coverage mode-invariant: "
              f"before={b['invariant']}  after={a['invariant']}   "
              f"worst switch drift: {wb:6.2f} -> {wa:5.2f} deg")
    jpath = os.path.join(args.out, "modeswitch_summary.json")
    with open(jpath, "w") as f:
        json.dump(summary, f, indent=2, default=str)
    print(f"\nwrote {jpath}")


if __name__ == "__main__":
    main()
