def _qadr(model, name):
    return int(model.jnt_qposadr[model.joint(name).id])


def _dofadr(model, name):
    return int(model.jnt_dofadr[model.joint(name).id])


def snapshot(rig):
    m, d = rig.qmodel, rig.qdata
    q = {j: float(d.qpos[_qadr(m, j)]) for j in ALL_JOINTS}
    palms = {s: float(d.body(f"{s}_palm").xpos[2]) for s in ("left", "right")}
    return q, palms


def drift(q0, q1):
    """{joint: |dq| in degrees}."""
    return {j: abs(np.degrees(q1[j] - q0[j])) for j in q0}


def group_max(dd):
    return {g: max(dd[j] for j in js) for g, js in GROUPS.items()}


def run_switch(rig_cls, method, control_type, region="arm", stiffness=STIFFNESS,
               settle_s=SETTLE_S, hold_s=HOLD_S, back_to_drive=False, trace=False):
    """Settle in Drive, switch space, hold. Returns the measured drift."""
    rig = rig_cls()
    try:
        n_settle = int(settle_s / TIMESTEP)
        n_hold = int(hold_s / TIMESTEP)
        for _ in range(n_settle):
            rig.tick()
        q0, p0 = snapshot(rig)
        ff_drive = rig.ff_dofs()

        rig.teleop.set_control_spec(method=method, control_type=control_type,
                                    region=region, stiffness=stiffness)
        ts, palm_t = [], []
        for k in range(n_hold):
            rig.tick()
            if trace and k % 5 == 0:
                _, p = snapshot(rig)
                ts.append(k * TIMESTEP)
                palm_t.append(1000.0 * (p0["right"] - p["right"]))
        ff_new = rig.ff_dofs()
        q1, p1 = snapshot(rig)

        out = {
            "drift": drift(q0, q1),
            "palm_mm": {s: 1000.0 * (p0[s] - p1[s]) for s in p0},
            "ff_drive": ff_drive,
            "ff_new": ff_new,
            "model": rig.qmodel,
        }
        if back_to_drive:
            rig.teleop.set_control_spec(method="navigation", control_type="impedance",
                                        region=region, stiffness=stiffness)
            for _ in range(n_hold):
                rig.tick()
            q2, p2 = snapshot(rig)
            out["drift_back"] = drift(q0, q2)
            out["palm_mm_back"] = {s: 1000.0 * (p0[s] - p2[s]) for s in p0}
        if trace:
            out["trace"] = (np.array(ts), np.array(palm_t))
        return out
    finally:
        rig.close()


def run_ratchet(rig_cls, cycles=5, dwell_s=2.0, stiffness=STIFFNESS):
    """Drive <-> Task, repeatedly. Returns the per-cycle cumulative drift."""
    rig = rig_cls()
    try:
        for _ in range(int(SETTLE_S / TIMESTEP)):
            rig.tick()
        q0, p0 = snapshot(rig)
        n = int(dwell_s / TIMESTEP)
        per_cycle = []
        for c in range(cycles):
            rig.teleop.set_control_spec(method="joint", control_type="impedance",
                                        region="arm", stiffness=stiffness)
            for _ in range(n):
                rig.tick()
            rig.teleop.set_control_spec(method="navigation", control_type="impedance",
                                        region="arm", stiffness=stiffness)
            for _ in range(n):
                rig.tick()
            q, p = snapshot(rig)
            dd = drift(q0, q)
            per_cycle.append({"cycle": c + 1, "groups": group_max(dd),
                              "palm_mm": 1000.0 * (p0["right"] - p["right"])})
        return per_cycle
    finally:
        rig.close()


