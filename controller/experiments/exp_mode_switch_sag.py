def e3_stiffness(rig_cls, sliders=(0.1, 0.3, 0.6, 1.0)):
    print(f"\n=== E3  STIFFNESS SWEEP -- {rig_cls.name} ===")
    print("Drive -> Task/Joint (Stiff) at each operator slider position (K = s*45)")
    print(f"{'slider':>8s}{'K':>8s}" + "".join(f"{g:>9s}" for g in GROUPS) + f"{'palmR':>9s}")
    out = []
    for s in sliders:
        K = s * 45.0
        r = run_switch(rig_cls, "joint", "impedance", "arm", stiffness=K)
        gm = group_max(r["drift"])
        print(f"{s:8.2f}{K:8.1f}" + "".join(f"{gm[g]:9.2f}" for g in GROUPS)
              + f"{r['palm_mm']['right']:9.2f}")
        out.append({"slider": s, "K": K, "groups": gm,
                    "palm_mm": r["palm_mm"]["right"]})
    return out


