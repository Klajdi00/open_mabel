def e1_coverage(rig_cls):
    print(f"\n=== E1  GRAVITY-COMP COVERAGE -- {rig_cls.name} ===")
    print("Which upper-body DoFs carry an applied effort in each control space?")
    rig = rig_cls()
    try:
        m = rig.qmodel
        want = {j: _dofadr(m, j) for j in ALL_JOINTS}
        modes = [("Drive", "navigation", "impedance", "arm"),
                 ("Task/Joint (Stiff)", "joint", "impedance", "arm"),
                 ("Task/Joint (Soft)", "joint", "compliance", "arm"),
                 ("Joint (Stiff, upper_body)", "joint", "impedance", "upper_body")]
        rows = {}
        for label, meth, typ, reg in modes:
            rig.teleop.set_control_spec(method=meth, control_type=typ, region=reg,
                                        stiffness=STIFFNESS)
            for _ in range(int(1.0 / TIMESTEP)):
                rig.tick()
            live = rig.ff_dofs()
            rows[label] = {j: (want[j] in live) for j in ALL_JOINTS}
        hdr = f"{'group':10s}" + "".join(f"{l[:22]:>24s}" for l, *_ in modes)
        print(hdr)
        for g, js in GROUPS.items():
            cells = []
            for label, *_ in modes:
                n = sum(1 for j in js if rows[label][j])
                cells.append(f"{n}/{len(js)}")
            print(f"{g:10s}" + "".join(f"{c:>24s}" for c in cells))
        tot = {l: sum(rows[l].values()) for l, *_ in modes}
        print(f"{'TOTAL':10s}" + "".join(f"{str(tot[l]) + '/' + str(len(ALL_JOINTS)):>24s}"
                                         for l, *_ in modes))
        invariant = len(set(tot.values())) == 1
        print(f"\nmode-invariant coverage: {'YES' if invariant else 'NO  <-- DEFECT'}")
        if not invariant:
            base = set(j for j in ALL_JOINTS if rows["Drive"][j])
            for label, *_ in modes[1:]:
                lost = sorted(base - set(j for j in ALL_JOINTS if rows[label][j]))
                if lost:
                    print(f"  {label}: LOSES gravity FF on {lost}")
        return rows, tot, invariant
    finally:
        rig.close()


