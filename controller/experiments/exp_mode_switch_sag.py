class _DirectRPC:
    """Stand-in for SimBridgeClient: dispatch straight into the SimWorld.

    The real client JSON-encodes over a socket to the bridge's RPC server, which
    calls exactly these SimWorld methods (simulation_bridge/rpc.py). Short-
    circuiting the socket keeps the command SEMANTICS (latched targets, effort
    timeout, deadman twist) while making the run deterministic."""

    def __init__(self, world):
        self.world = world
        self.calls = {}

    def try_call(self, op, **kw):
        self.calls[op] = self.calls.get(op, 0) + 1
        fn = getattr(self.world, op, None)
        return fn(**kw) if fn is not None else None

    def close(self):
        pass


class SplitRig:
    """The DEFAULT deployment: gateway (control law, kinematic mirror) + a
    separate physics owner, coupled by (targets, effort, twist, wrench)."""

    name = "split (sim:bridge)"
    CMD_HZ = 120.0                    # server/plant.py SimBridgePlant.CMD_HZ

    def __init__(self, instance="wbcexp"):
        from mabel import MabelTeleop
        from simulation_bridge.engine import SimWorld
        from plant import SimBridgePlant

        # --- the physics owner (its own process in production) ---
        os.environ.setdefault("MABEL_SIM_SENSORS", "0")
        self.world = SimWorld(scene=SCENE, instance=instance)
        self.world.model.opt.timestep = TIMESTEP

        # --- the gateway: kinematic mirror + the one control law ---
        self.model = mujoco.MjModel.from_xml_path(SCENE)
        self.model.opt.timestep = TIMESTEP
        self.data = mujoco.MjData(self.model)
        mujoco.mj_forward(self.model, self.data)
        self.teleop = MabelTeleop(self.model, self.data)
        self.teleop.controller.init_hold()
        self.teleop.controller.settle_done()

        self.plant = SimBridgePlant(self.model, self.data)
        self.plant.rpc = _DirectRPC(self.world)
        self.plant._mm = self.world.state        # the published state memmap, live
        self.plant._mm_legacy = False

        self._t = 0.0
        self._rpc_t = -1e9
        for _ in range(300):
            self.tick()

    @property
    def qmodel(self):
        return self.world.model

    @property
    def qdata(self):
        return self.world.data

    def tick(self):
        # gateway substep: mirror in, control law, project out (rate-gated)
        self.plant.read_state()
        try:
            cmd = self.teleop.update(None, None, TIMESTEP)
        except Exception:
            cmd = None
        if cmd is not None and (self._t - self._rpc_t) >= (1.0 / self.CMD_HZ):
            self._rpc_t = self._t
            self.plant._last_cmd_t = 0.0         # gate on SIM time, not wall time
            self.plant.advance(cmd, None, self.teleop.wbc.active)
        # physics owner substep
        self.world._intake()
        self.world._apply_commands()
        mujoco.mj_step(self.world.model, self.world.data)
        self.world._publish()
        self._t += TIMESTEP

    def ff_dofs(self):
        """DoFs the PHYSICS OWNER is actually applying effort to -- i.e. what
        survived the RPC hop. This is the number that matters."""
        return set(np.nonzero(np.abs(self.world.data.qfrc_applied) > 1e-9)[0].tolist())

    def close(self):
        try:
            self.world.stop()
        except Exception:
            pass
        # SimWorld claims an exclusive flock for its instance and holds the fd
        # for the process lifetime; a harness that builds one rig per data point
        # must hand it back or the SECOND rig is refused.
        try:
            os.close(self.world._lock_fd)
        except Exception:
            pass


