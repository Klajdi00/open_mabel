def _style(ax):
    ax.grid(alpha=0.25, lw=0.6)
    ax.set_axisbelow(True)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)


def fig_e2(before, after, rig_label, path):
    labels = list(GROUPS)
    x = np.arange(len(labels))
    w = 0.38
    fig, axes = plt.subplots(1, len(TRANSITIONS), figsize=(13, 3.4), sharey=True)
    for ax, (label, *_ ) in zip(axes, TRANSITIONS):
        b = [before[label]["groups"][g] for g in labels]
        a = [after[label]["groups"][g] for g in labels]
        ax.bar(x - w / 2, b, w, label="before", color="#c44e52")
        ax.bar(x + w / 2, a, w, label="after", color="#4c72b0")
        ax.set_xticks(x)
        ax.set_xticklabels(labels, rotation=35, ha="right", fontsize=8)
        ax.set_title(label.replace("Drive -> ", ""), fontsize=9)
        _style(ax)
    axes[0].set_ylabel("max joint drift across the\nswitch [deg]")
    axes[0].legend(fontsize=8, frameon=False)
    fig.suptitle(f"Control-space switch: upper-body drift, {rig_label}", fontsize=11)
    fig.tight_layout()
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)
    print(f"  wrote {path}")


