#!/usr/bin/env python3
"""
exp_mode_switch_sag.py -- does the upper body SAG when the operator switches
control space (Drive -> Task / Joint)?

Operator report (2026-07-24): "when I switch from drive to joint or task space
the robot arm will sag". In the Simulation Control Center those three buttons
send exactly one wire field each (web_gui/simulation_control_center/web/js/
app.js:869):

    Drive  ->  method = "navigation"      (kinematic path: TeleopEngine)
    Task   ->  method = "joint"           (torque path: WBCEngine)   <- ctl.space=='task'
    Joint  ->  method = "joint"           (torque path: WBCEngine)

with type = impedance (Stiff), region = "arm", stiffness = slider*45 = 27 N.m/rad
at the default 0.6 slider. Nothing about the ARMS is supposed to change -- the
operator is only choosing which reference GENERATOR is live.

THE DEFECT this script measures. Gravity compensation was implemented TWICE, in
two places, over two DIFFERENT sets of joints:

  * navigation / retarget (TeleopEngine.update) writes a gravity feed-forward
    over `model_utils.gravity_dofs(model)` -- the 22 actuated upper-body DoFs:
    lift x2, torso, neck x3, arms 2x7, ORCA wrists x2.
  * joint / wrist (WBCEngine.step) calls plant.begin(), which ZEROES the whole
    qfrc_applied vector, then re-applies effort only to `self.managed` -- the 14
    arm joints. The wrists are deliberately excluded from the torque law
    (_managed_for: they ring up under the split-process feedback delay), and the
    torso is unmanaged in the "arm" region, and the lift is unmanaged unless it
    is freed.

So the moment the operator leaves Drive, 8 upper-body DoFs silently lose their
gravity feed-forward and settle to their servos' tau_g/kp error. That is the sag,
and it is a MODE-DEPENDENT control law -- which is the thing the operator asked
to be made mode-invariant.

Two deployments are measured, because they fail differently:

  A. IN-PROCESS ("sim:mujoco" / the Control Lab bench): MabelTeleop owns MjData,
     so WBCEngine.enter() really does neutralise the arm servos and the torque
     law really is the only thing holding the arms.
  B. SPLIT ("sim:bridge" -- the DEFAULT, what server/run.sh runs, and the
     structural twin of the real robot): the gateway holds a kinematic MIRROR and
     ships (targets, effort) to the physics owner over RPC at 120 Hz. Here the
     gateway's OWN servo-neutralisation is a no-op, and -- the second half of the
     defect -- SimBridgePlant.advance() only transmits the effort channel
     `if wbc_active`, so in Drive the gravity feed-forward the TeleopEngine
     computes is discarded and never reaches the robot at all.

Both are emulated with the REAL code (server/plant.py:SimBridgePlant and
simulation_bridge/engine.py:SimWorld), coupled in-process through a direct-call
stand-in for the RPC socket so the run is deterministic and needs no daemons.

Experiments
  E1 COVERAGE   which upper-body DoFs carry a gravity feed-forward, per mode.
                The invariant: the set must be mode-INVARIANT.
  E2 SWITCH SAG per-joint drift + palm height drop across every space switch,
                on both deployments.
  E3 STIFFNESS  E2's worst joint vs the operator's stiffness slider (K = s*45).
  E4 RATCHET    5x Drive<->Task cycles: does the error compound?
  E5 TRANSIENT  palm height vs time through the switch (what the eye sees).

Run:
    python experiments/exp_mode_switch_sag.py              # all + figures
    python experiments/exp_mode_switch_sag.py --quick      # E1/E2 only, no figures
The BEFORE curves are regenerated by the same code with the fix disabled:
    MABEL_WBC_GRAV_UNMANAGED=0 python experiments/exp_mode_switch_sag.py
(the script sweeps that flag itself for the comparison figures).
"""
