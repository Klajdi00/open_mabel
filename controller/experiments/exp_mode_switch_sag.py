class InProcessRig:
    """MabelTeleop owns the MjData it steps: servo neutralisation is real."""

    name = "in-process (sim:mujoco)"

    def __init__(self):
        from mabel import MabelTeleop
        self.model = mujoco.MjModel.from_xml_path(SCENE)
        self.model.opt.timestep = TIMESTEP
        self.data = mujoco.MjData(self.model)
        mujoco.mj_forward(self.model, self.data)
        self.teleop = MabelTeleop(self.model, self.data)
        self.teleop.controller.init_hold()
        self.teleop.controller.settle_done()
        for _ in range(300):
            mujoco.mj_step(self.model, self.data)

    # the physics state an observer measures
    @property
    def qmodel(self):
        return self.model

    @property
    def qdata(self):
        return self.data

    def tick(self):
        try:
            self.teleop.update(None, None, TIMESTEP)
        except Exception:
            pass
        mujoco.mj_step(self.model, self.data)

    def ff_dofs(self):
        """DoFs currently carrying a nonzero applied effort (gravity FF + torque law)."""
        return set(np.nonzero(np.abs(self.data.qfrc_applied) > 1e-9)[0].tolist())

    def close(self):
        pass


