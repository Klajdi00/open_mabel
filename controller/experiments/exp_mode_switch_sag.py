TRANSITIONS = [
    ("Drive -> Task/Joint (Stiff)", "joint", "impedance", "arm"),
    ("Drive -> Task/Joint (Soft)", "joint", "compliance", "arm"),
    ("Drive -> Wrist/Task IK (Stiff)", "wrist", "impedance", "arm"),
    ("Drive -> Joint upper_body (Stiff)", "joint", "impedance", "upper_body"),
]


def e2_switch(rig_cls):
    print(f"\n=== E2  SWITCH SAG -- {rig_cls.name} ===")
    print(f"settle {SETTLE_S:.0f}s in Drive, switch, hold {HOLD_S:.0f}s, K={STIFFNESS:.0f} N.m/rad")
    print(f"{'transition':36s}" + "".join(f"{g:>9s}" for g in GROUPS)
          + f"{'palmR':>9s}{'back':>9s}")
    print(f"{'':36s}" + "".join(f"{'[deg]':>9s}" for _ in GROUPS)
          + f"{'[mm]':>9s}{'[deg]':>9s}")
    results = {}
    for label, meth, typ, reg in TRANSITIONS:
        r = run_switch(rig_cls, meth, typ, reg, back_to_drive=True)
        gm = group_max(r["drift"])
        back = max(r["drift_back"].values())
        print(f"{label:36s}" + "".join(f"{gm[g]:9.2f}" for g in GROUPS)
              + f"{r['palm_mm']['right']:9.2f}{back:9.2f}")
        results[label] = {"groups": gm, "palm_mm": r["palm_mm"],
                          "worst": max(r["drift"].values()),
                          "worst_joint": max(r["drift"], key=r["drift"].get),
                          "back": back,
                          "per_joint": r["drift"]}
    return results


