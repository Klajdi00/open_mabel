// host_link.h — UDP host interface for one robot (host <-> Teensy).
//
// Header-only and included ONLY by src/main.cpp, so the nanopb dependency stays out
// of the diagnostic/provision sketches. All work runs in loop() context (QNEthernet
// is not ISR-safe — never call from a CAN RX handler).
//
// Generic over any Robot: the actuator count, names and watchdog/stream timing all
// come from the loaded RobotConfig, so one binary serves any robot. Wire messages
// carry a runtime actuator count (proto repeated fields are dynamic, max MAX_ACTUATORS).
//
// Wire protocol: one UDP datagram per message, each prefixed with a 1-byte type tag
// (see Tag below) followed by the nanopb-encoded body. See proto/robot.proto.
//
// Data-exchange policy (mirrors the base module's HostLink, adapted to DAMIAO MIT):
//   * Commands (per-actuator MIT setpoints) are decoded and CACHED on receipt.
//   * service() streams those setpoints to CAN at the control/stream rate. Each MIT
//     frame is BOTH the command and the feedback request (DM is request/response),
//     so one tick drives the actuators AND refreshes the State the host reads.
//   * State is streamed to the learned host endpoint at the same rate; getState()
//     on the host is a pure read of the latest packet (no round trip).
//   * Health is request/reply (HealthRequest -> Health), kept off the hot path.
//
// Safety — the DM comm-loss watchdog is OFF (timeout=0), so motors hold their last
// MIT command if frames stop. We therefore manage output EXPLICITLY:
//   * Connection watchdog (conn_watchdog_ms): on the connected->disconnected edge we
//     disableAll() (motors go limp = fail-safe); on connect we enableAll().
//     ⚠ A heavy arm goes LIMP on host loss — keep it supported / be ready.
//   * Command watchdog (cmd_watchdog_ms): while connected, a stale command is
//     replaced by a safe damping hold (kp=0, kd=per-actuator default, t_ff=0) so a
//     monitor-only host keeps telemetry alive without driving the robot anywhere.

#ifndef ROBOT_HOST_LINK_H
#define ROBOT_HOST_LINK_H

#include <Arduino.h>
#include <QNEthernet.h>
#include <pb_decode.h>
#include <pb_encode.h>

#include "robot.pb.h"     // generated by nanopb from proto/robot.proto
#include "Robot.h"

class RobotHostLink {
public:
  // Datagram type tags (first payload byte). Must match proto/robot.proto.
  enum Tag : uint8_t {
    kTagCommand       = 0x01,  // host -> Teensy
    kTagHealthRequest = 0x02,  // host -> Teensy
    kTagHello         = 0x03,  // host -> Teensy
    kTagState         = 0x10,  // Teensy -> host
    kTagHealth        = 0x11,  // Teensy -> host
    kTagRobotInfo     = 0x12,  // Teensy -> host (reply to Hello)
  };

  static constexpr uint32_t kLiveWindowMs = 50;   // feedback fresher than this => "live"

  explicit RobotHostLink(Robot& robot) : robot_(robot) {}

  // Call after robot.begin(): adopts the loaded config's network port + timing.
  void begin(uint16_t localPort) {
    const RobotConfig &c = robot_.config();
    connWatchdogMs_  = c.conn_watchdog_ms;
    cmdWatchdogMs_   = c.cmd_watchdog_ms;
    defaultStreamHz_ = c.stream_default_hz;
    maxStreamHz_     = c.stream_max_hz;
    localPort_       = localPort;
    udp_.begin(localPort_);
    streamPeriodUs_  = 1000000UL / defaultStreamHz_;
  }

  // Call every loop(): drain inbound datagrams (cache commands, answer health/hello).
  void poll() {
    int n = udp_.parsePacket();
    if (n < 0) return;                 // QNEthernet: negative = no packet (0 = valid empty)
    const uint8_t* p = udp_.data();
    size_t len = udp_.size();
    if (len < 1) return;
    IPAddress rip = udp_.remoteIP();
    uint16_t rport = udp_.remotePort();
    uint8_t tag = p[0];
    const uint8_t* body = p + 1;
    size_t blen = len - 1;
    lastPacketMs_ = millis();
    ++rxCount_;

    switch (tag) {
      case kTagCommand:       onCommand(body, blen);                   break;
      case kTagHealthRequest: onHealthRequest(body, blen, rip, rport); break;
      case kTagHello:         onHello(body, blen, rip, rport);         break;
      default: /* unknown tag — ignore */ break;
    }
  }

  // Call every loop(): manage enable/disable, stream MIT setpoints + State.
  void service() {
    uint32_t now = millis();
    bool connected = haveHost_ && (now - lastPacketMs_ < connWatchdogMs_);

    // Output gating on the connection edges.
    if (connected && !enabled_) { robot_.enableAll();  enabled_ = true; }
    if (!connected && enabled_) { robot_.disableAll(); enabled_ = false; }
    // `enabled_` is a robot-wide EDGE, so on its own it energizes exactly once per
    // connect. Anything that joins afterwards — powered late, replugged, or rescued by
    // serviceOffline() — would never be energized again for the life of the connection.
    // Sweep for those every tick; the Robot rate-limits the actual repair.
    if (connected) robot_.serviceEnable();
    if (!connected) return;     // disconnected -> motors disabled, nothing to stream

    // One control+stream tick: push setpoints to CAN (which also elicits feedback),
    // then send the freshly-cached State to the host.
    uint32_t nowUs = micros();
    if ((uint32_t)(nowUs - lastStreamUs_) >= streamPeriodUs_) {
      lastStreamUs_ = nowUs;
      bool cmdFresh = haveCmd_ && (now - lastCmdMs_ < cmdWatchdogMs_);
      applyCommand(cmdFresh);
      sendState();
    }
  }

  // ---- telemetry accessors (for the serial print in main.cpp) ----
  bool     connected() const { return haveHost_ && (millis() - lastPacketMs_ < connWatchdogMs_); }
  bool     enabled() const   { return enabled_; }
  uint32_t lastSeq() const   { return lastSeq_; }
  uint32_t rxCount() const   { return rxCount_; }
  uint32_t txCount() const   { return txCount_; }
  uint16_t streamHz() const  { return streamPeriodUs_ ? (uint16_t)(1000000UL / streamPeriodUs_) : 0; }

private:
  // ---- inbound handlers ----
  void onCommand(const uint8_t* body, size_t blen) {
    robot_Command cmd = robot_Command_init_zero;
    pb_istream_t is = pb_istream_from_buffer(body, blen);
    if (!pb_decode(&is, robot_Command_fields, &cmd)) return;
    cmd_ = cmd;                 // cache; streamed to CAN in service() at the control rate
    lastSeq_ = cmd.seq;
    haveCmd_ = true;
    lastCmdMs_ = millis();
  }

  void onHealthRequest(const uint8_t* body, size_t blen, IPAddress rip, uint16_t rport) {
    robot_HealthRequest req = robot_HealthRequest_init_zero;
    pb_istream_t is = pb_istream_from_buffer(body, blen);
    pb_decode(&is, robot_HealthRequest_fields, &req);  // seq optional
    sendHealth(req.seq, rip, rport);
  }

  void onHello(const uint8_t* body, size_t blen, IPAddress rip, uint16_t rport) {
    robot_Hello hello = robot_Hello_init_zero;
    pb_istream_t is = pb_istream_from_buffer(body, blen);
    pb_decode(&is, robot_Hello_fields, &hello);
    host_ = rip;
    hostPort_ = rport;
    haveHost_ = true;
    uint16_t hz = hello.stream_hz ? hello.stream_hz : defaultStreamHz_;
    if (hz > maxStreamHz_) hz = maxStreamHz_;
    streamPeriodUs_ = 1000000UL / hz;
    sendRobotInfo(rip, rport);   // advertise the layout so the host builds itself
  }

  // ---- command application ----
  // Build each actuator's command (fresh host setpoint, or a safe damping hold when
  // stale) and push it to CAN. sendCommand sends the MIT frame, which also requests
  // feedback for the next State.
  void applyCommand(bool fresh) {
    size_t n = robot_.count();
    for (size_t i = 0; i < n; ++i) {
      if (fresh && i < cmd_.pos_count) {
        Robot::ActuatorCommand c{};
        c.pos = cmd_.pos[i]; c.vel = cmd_.vel[i];
        c.kp  = cmd_.kp[i];  c.kd  = cmd_.kd[i];  c.t_ff = cmd_.t_ff[i];
        robot_.sendCommand(i, c);
      } else {
        // Ask the ACTUATOR for its own safe hold rather than assuming kp=0/kd=default/
        // pos=0 means "safe" everywhere. It does for a DM-J in MIT mode; pushed through
        // a DYNAMIXEL position servo the identical numbers mean "drive to raw zero at
        // full speed", turning the fail-safe into the worst command the joint can get.
        robot_.sendHold(i);
      }
    }
  }

  // ---- outbound encoders ----
  // Advertise the loaded robot layout (from RobotConfig) so the host can build its
  // actuator surface dynamically with no hard-coded assumptions.
  void sendRobotInfo(IPAddress rip, uint16_t rport) {
    const RobotConfig &cfg = robot_.config();
    robot_RobotInfo info = robot_RobotInfo_init_zero;
    snprintf(info.name, sizeof(info.name), "%s", cfg.name);
    info.stream_default_hz = cfg.stream_default_hz;
    info.stream_max_hz     = cfg.stream_max_hz;
    size_t n = robot_.count();
    info.actuators_count = n;
    for (size_t i = 0; i < n; ++i) {
      const ActuatorConfig &a = cfg.actuators[i];
      robot_ActuatorInfo &d = info.actuators[i];
      snprintf(d.name,  sizeof(d.name),  "%s", a.name);
      snprintf(d.model, sizeof(d.model), "%s", a.model);
      d.bus        = a.bus;
      d.can_id     = a.can_id;
      d.mst_id     = a.mst_id;
      // The ranges read from the motor at begin() — the same scale commands are
      // encoded against. An OFFLINE actuator never answered, so it has no known
      // range: publish 0 rather than the struct's fallback initialisers, which
      // are a different motor's numbers and would read as real. 0 is unambiguous
      // ("unknown"), and pairs with the actuator reading clear in live_mask.
      //
      // A DYNAMIXEL actuator is ONLINE and still publishes 0 here — not because it
      // failed, but because its protocol has no MIT fixed-point scale for these to
      // describe. Same signal, same meaning ("this number does not exist"), which
      // is why DxlActuator zeroes them at construction rather than relying on this
      // `on ?` guard. See ActuatorLimits.h.
      const ActuatorLimits &lim = robot_.limits(i);
      const bool on = robot_.online(i);
      d.p_max      = on ? lim.p_max : 0.0f;
      d.v_max      = on ? lim.v_max : 0.0f;
      d.t_max      = on ? lim.t_max : 0.0f;
      d.kp_max     = lim.kp_max;
      d.kd_max     = lim.kd_max;
      d.default_kp = a.default_kp;
      d.default_kd = a.default_kd;
    }
    sendTagged(kTagRobotInfo, robot_RobotInfo_fields, &info, rip, rport);
  }

  void sendState() {
    robot_State st = robot_State_init_zero;
    st.seq  = lastSeq_;
    st.t_us = micros();
    size_t n = robot_.count();
    st.actuators_count = n;
    uint32_t mask = 0;
    for (size_t i = 0; i < n; ++i) {
      Robot::ActuatorState s = robot_.state(i);
      st.actuators[i].position = s.pos;
      st.actuators[i].velocity = s.vel;
      st.actuators[i].torque   = s.torque;
      if (robot_.feedbackAgeMs(i) < kLiveWindowMs) mask |= (1u << i);
    }
    st.live_mask = mask;
    sendTagged(kTagState, robot_State_fields, &st, host_, hostPort_);
  }

  void sendHealth(uint32_t seq, IPAddress rip, uint16_t rport) {
    robot_Health h = robot_Health_init_zero;
    h.seq  = seq;
    h.t_us = micros();
    size_t n = robot_.count();
    h.actuators_count = n;
    for (size_t i = 0; i < n; ++i) {
      Robot::ActuatorState s = robot_.state(i);
      uint32_t age = robot_.feedbackAgeMs(i);
      h.actuators[i].err      = s.err;
      h.actuators[i].t_mos    = s.t_mos;
      h.actuators[i].t_rotor  = s.t_rotor;
      // NOT `s.err == 1` any more. That is the DAMIAO "enabled OK" nibble, and a
      // DYNAMIXEL reports Hardware Error Status 0 when healthy — so the old formula
      // reported a perfectly good servo as de-energized forever, which is exactly
      // the signature of the `late_join_enable` fault already on the board. Each
      // actuator now answers for itself (Robot::enabled).
      h.actuators[i].enabled  = robot_.enabled(i);
      h.actuators[i].live     = (age < kLiveWindowMs);
      h.actuators[i].stale_ms = age;
    }
    sendTagged(kTagHealth, robot_Health_fields, &h, rip, rport);
  }

  // Encode `src` (nanopb message) into tx_ behind a 1-byte tag and send it.
  template <typename T>
  void sendTagged(uint8_t tag, const pb_msgdesc_t* fields, const T* src,
                  IPAddress ip, uint16_t port) {
    tx_[0] = tag;
    pb_ostream_t os = pb_ostream_from_buffer(tx_ + 1, sizeof(tx_) - 1);
    if (!pb_encode(&os, fields, src)) return;
    udp_.send(ip, port, tx_, os.bytes_written + 1);
    ++txCount_;
  }

  Robot& robot_;
  qindesign::network::EthernetUDP udp_{4};  // RX queue depth 4 (keep latest under burst)
  uint16_t localPort_ = 0;

  // Timing/limits adopted from RobotConfig in begin().
  uint32_t connWatchdogMs_  = 250;
  uint32_t cmdWatchdogMs_   = 150;
  uint16_t defaultStreamHz_ = 1000;
  uint16_t maxStreamHz_     = 1000;

  IPAddress host_;
  uint16_t  hostPort_ = 0;
  bool      haveHost_ = false;
  bool      enabled_  = false;
  uint32_t  streamPeriodUs_ = 5000;  // 200 Hz default until begin()/Hello

  robot_Command cmd_ = robot_Command_init_zero;
  bool     haveCmd_ = false;
  uint32_t lastSeq_ = 0;
  uint32_t lastPacketMs_ = 0;
  uint32_t lastCmdMs_ = 0;
  uint32_t lastStreamUs_ = 0;
  uint32_t rxCount_ = 0;
  uint32_t txCount_ = 0;

  // Sized for the largest message: RobotInfo with MAX_ACTUATORS descriptors
  // (~95 B each) — State/Health/Command are far smaller.
  // Outbound packet scratch. MUST exceed the largest encodable message (RobotInfo, the
  // self-describing handshake — it carries a name + model string and 5 limits PER
  // actuator, so it grows ~90 B per actuator and is far larger than the streamed State).
  // On overflow pb_encode() fails and sendTagged() returns SILENTLY: the host would
  // simply never receive the handshake, with nothing logged. The static_assert below
  // converts that into a build error, so raising MAX_ACTUATORS can never reintroduce it.
  uint8_t tx_[4096];
  static_assert(robot_RobotInfo_size + 1 <= sizeof(tx_),
                "tx_ too small for RobotInfo at the current MAX_ACTUATORS — "
                "enlarge tx_ (the +1 is the framing tag byte)");
};

#endif  // ROBOT_HOST_LINK_H
