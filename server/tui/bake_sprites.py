#!/usr/bin/env python3
"""
bake_sprites.py — bake the cockpit's robot sprite from the CANONICAL MJCF.

Renders simulation/mabel_mujoco/models/mabel_full.xml offscreen from an
isometric camera and quantizes to the cockpit's retro palette, producing
tui/sprite_frames.py (a zlib+base64 blob the stdlib-only cockpit can load).
The sprite therefore LOOKS like MABEL because it IS MABEL — same source of
truth as the URDF/GLB/rig pipeline. Re-run after any visual MJCF change:

    ~/anaconda3/bin/python3 tui/bake_sprites.py        # ~1 min, 256 frames

Grid: 8 camera azimuths (45° steps — the cockpit spins the robot with odom
yaw) × 4 arm stances per side (nearest-stance classified from the live
a1/a2 joints, table below == the classifier's table) × 2 lift levels.
"""
from __future__ import annotations

import base64
import json
import os
import sys
import zlib

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
MJCF = os.path.join(ROOT, "simulation", "mabel_mujoco", "models", "mabel_full.xml")
OUT = os.path.join(HERE, "sprite_frames.py")

# two baked resolutions: SMALL for normal terminals, HD for fullscreen
SIZES = [(38, 54), (54, 76)]
SS = 8                       # supersample factor
AZIMUTHS = list(range(0, 360, 45))
LIFTS = [0.08, 0.55]         # column travel (m): low / high

# Arm stances as ABSOLUTE (a1, a2) qpos per side (probed against the model;
# the model's refs are asymmetric, so left/right tables differ). The cockpit
# classifies the LIVE (a1, a2) to the nearest row of this same table.
STANCES = {
    "left":  {"down": (0.9, 0.0), "ready": (0.0, 0.0),
              "up": (-1.0, 0.0), "out": (0.0, 0.9)},
    "right": {"down": (0.0, 0.0), "ready": (0.0, -0.9),
              "up": (1.0, 0.0), "out": (-0.9, 0.0)},
}
POSE_NAMES = ("down", "ready", "up", "out")

# palette (keys shared with sprite.py) as target RGB anchors
GREY_LADDER = [("k", 26), ("K", 44), ("g", 84), ("G", 138), ("w", 192), ("W", 236)]


def quantize(block: np.ndarray) -> str:
    """8×8 RGB block → one palette key ('.' = background)."""
    px = block.reshape(-1, 3).astype(np.float32)
    lum = px.mean(axis=1)
    solid = px[lum > 14]
    if len(solid) < len(px) * 0.22:
        return "."
    r, g, b = solid.mean(axis=0)
    # chroma picks the accent colors (orange wrists/markers, yellow lidar)
    if r > 90 and r > g * 1.35 and g > b * 1.15:
        return "O" if r > 150 else "o"
    if r > 110 and g > 95 and b < g * 0.6:
        return "Y" if r > 170 else "y"
    # grey ladder with a strong lift: the MJCF materials render dark, the
    # real shells are light — gamma-brighten so the sprite reads white/grey
    v = 255.0 * (max(r, g, b) / 255.0) ** 0.45
    best = min(GREY_LADDER, key=lambda kv: abs(kv[1] - v))
    return best[0]


def main() -> int:
    import mujoco

    m = mujoco.MjModel.from_xml_path(MJCF)
    # cockpit-only accent: paint the HEAD (sensor block) orange so the sprite
    # gets lit orange shading on its front — bake-time recolor, never the model
    for gi in range(m.ngeom):
        if m.body(m.geom_bodyid[gi]).name in ("head", "head_mount"):
            a = m.geom_rgba[gi][3]
            m.geom_matid[gi] = -1
            m.geom_rgba[gi] = [0.95, 0.45, 0.08, a if a > 0 else 1.0]
    d = mujoco.MjData(m)
    jadr = {m.joint(i).name: m.jnt_qposadr[m.joint(i).id] for i in range(m.njnt)}
    cam = mujoco.MjvCamera()
    cam.elevation, cam.distance = -18, 2.45
    cam.lookat[:] = [0.0, 0.0, 0.7]

    sets = []
    for SPR_W, SPR_H in SIZES:
        r = mujoco.Renderer(m, height=SPR_H * SS, width=SPR_W * SS)
        frames = bake_size(m, d, jadr, r, cam, SPR_W, SPR_H)
        sets.append({"w": SPR_W, "h": SPR_H, "frames": frames})
        r.close()

    payload = {"azimuths": AZIMUTHS, "poses": list(POSE_NAMES),
               "lifts": LIFTS, "stances": STANCES, "sets": sets}
    blob = base64.b64encode(zlib.compress(
        json.dumps(payload).encode(), 9)).decode()
    with open(OUT, "w") as f:
        f.write('"'+'""sprite_frames.py — GENERATED by bake_sprites.py from the\n'
                "canonical MJCF (mabel_full.xml). Do not hand-edit; re-run the\n"
                'baker after visual MJCF changes (see the root README sync rule)."'+'""\n'
                "import base64, json, zlib\n\n"
                f'_BLOB = "{blob}"\n\n'
                "DATA = json.loads(zlib.decompress(base64.b64decode(_BLOB)))\n")
    kb = os.path.getsize(OUT) / 1024
    print(f"wrote {OUT} ({kb:.0f} KB, {sum(len(s['frames']) for s in sets)} frames)")
    return 0


def bake_size(m, d, jadr, r, cam, SPR_W, SPR_H):
    import mujoco
    frames: dict[str, str] = {}
    n = 0
    for li, lift in enumerate(LIFTS):
        for pl in POSE_NAMES:
            for pr in POSE_NAMES:
                mujoco.mj_resetDataKeyframe(m, d, 0)
                d.qpos[jadr["Lift Lower"]] = lift / 2
                d.qpos[jadr["Lift Upper"]] = lift / 2
                for side, pose in (("Left", pl), ("Right", pr)):
                    a1, a2 = STANCES[side.lower()][pose]
                    d.qpos[jadr[f"{side} Arm 1"]] = a1
                    d.qpos[jadr[f"{side} Arm 2"]] = a2
                mujoco.mj_forward(m, d)
                for ai, az in enumerate(AZIMUTHS):
                    cam.azimuth = az
                    r.update_scene(d, camera=cam)
                    img = r.render()
                    rows = []
                    for y in range(SPR_H):
                        row = []
                        for x in range(SPR_W):
                            row.append(quantize(
                                img[y * SS:(y + 1) * SS, x * SS:(x + 1) * SS]))
                        rows.append("".join(row))
                    frames[f"{ai}|{pl}|{pr}|{li}"] = "\n".join(rows)
                    n += 1
                    if n % 64 == 0:
                        print(f"  {SPR_W}x{SPR_H}: {n}/256 frames", flush=True)
    return frames


if __name__ == "__main__":
    sys.exit(main())
