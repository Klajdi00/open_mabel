#!/usr/bin/env python3
"""
gen_env_textures2.py -- tileable textures for the EXTENDED scene library
(supermarket, restaurants, cafes, gym, washroom, living rooms, full house,
golf, front yard, rooftop lounge, airport, and the dynamic city streets).

Companion to gen_home_textures.py (kitchen/home set) and gen_env_textures.py
(factory/office/outdoor set). Writes PNGs into assets/textures/ referenced by
scenes/mabel_<env>.xml generated by scripts/tools/scenegen/:

    asphalt.png        worn asphalt road surface (streets, parking)
    sidewalk.png       big concrete pavement slabs with expansion joints
    sand.png           raked bunker sand (golf)
    fairway.png        mowed turf with alternating mow stripes (golf/yard)
    rubber_floor.png   black speckled rubber gym tiles
    tile_checker.png   red/white checkerboard (fast food)
    tile_small.png     small white ceramic tiles + grout (washroom)
    awning_red.png     red/white canopy stripes (cafe, storefronts)
    awning_green.png   green/cream canopy stripes (second cafe)
    products.png       packed supermarket shelf front (colorful boxes)
    menu_board.png     dark emissive menu board with item lines
    facade.png         window-grid building face (street canyons)
    storefront.png     ground-floor shop glass + mullions
    tablecloth.png     ivory linen weave (fine dining)
    water.png          pool water with caustic ripples (lounge)
    crosswalk.png      zebra stripes across asphalt (crossings)

No network or heavy deps -- pure numpy + PIL, fixed seed. Run from repo root:
    python3 scripts/tools/gen_env_textures2.py
"""
import os

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "assets", "textures"))
os.makedirs(OUT, exist_ok=True)
RNG = np.random.default_rng(23)          # fixed seed -> reproducible textures


def value_noise(h, w, octaves=5, persistence=0.5):
    """Tileable multi-octave value noise in [0,1] via upsampled random grids."""
    acc = np.zeros((h, w), np.float32)
    amp, tot = 1.0, 0.0
    for o in range(octaves):
        n = 2 ** (o + 1)
        g = RNG.random((n, n)).astype(np.float32)
        g = np.vstack([g, g[:1]]); g = np.hstack([g, g[:, :1]])   # wrap for tiling
        up = np.asarray(Image.fromarray((g * 255).astype(np.uint8))
                        .resize((w, h), Image.BICUBIC), np.float32) / 255.0
        acc += amp * up
        tot += amp; amp *= persistence
    acc /= tot
    return (acc - acc.min()) / (np.ptp(acc) + 1e-9)


def save(name, arr):
    Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8)).save(os.path.join(OUT, name))
    print("wrote", os.path.join(OUT, name))


def asphalt():
    H = W = 512
    base = np.array([58, 58, 61], np.float32)
    n = value_noise(H, W, octaves=6)
    wear = value_noise(H, W, octaves=3)
    col = base[None, None, :] + (n[..., None] - 0.5) * 18 + (wear[..., None] - 0.5) * 14
    speck = (RNG.random((H, W)) > 0.975)[..., None] * np.float32(26)   # aggregate glint
    col += speck
    cracks = (value_noise(H, W, octaves=7) > 0.86)[..., None] * np.float32(-18)
    col += cracks
    save("asphalt.png", col)


def sidewalk():
    H = W = 512
    base = np.array([168, 165, 158], np.float32)
    n = value_noise(H, W, octaves=6)
    col = base[None, None, :] + (n[..., None] - 0.5) * 20
    col -= (RNG.random((H, W)) > 0.988)[..., None] * np.float32(30)    # gum/stains
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)
    for v, k in ((x / W, 2), (y / H, 2)):                              # 2x2 slabs / tile
        d = np.minimum((v * k) % 1.0, 1 - (v * k) % 1.0)
        col -= np.clip(1 - d / 0.010, 0, 1)[..., None] * 60
    save("sidewalk.png", col)


def sand():
    H = W = 512
    base = np.array([222, 205, 168], np.float32)
    n = value_noise(H, W, octaves=6)
    col = base[None, None, :] + (n[..., None] - 0.5) * 22
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)
    rake = np.sin((x + 40 * value_noise(H, W, 3)) / W * 2 * np.pi * 24) * 6  # rake lines
    col += rake[..., None]
    save("sand.png", col)


def fairway():
    H = W = 512
