def rubber_floor():
    H = W = 512
    base = np.array([44, 45, 48], np.float32)
    n = value_noise(H, W, octaves=5)
    col = base[None, None, :] + (n[..., None] - 0.5) * 10
    fleck = RNG.random((H, W))
    col += ((fleck > 0.987)[..., None] * np.array([70, 70, 75], np.float32))   # gray fleck
    col += ((fleck < 0.004)[..., None] * np.array([90, 30, 25], np.float32))   # red fleck
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)
    for v in (x / W, y / H):
        d = np.minimum((v * 2) % 1.0, 1 - (v * 2) % 1.0)
        col -= np.clip(1 - d / 0.008, 0, 1)[..., None] * 22            # tile seams
    save("rubber_floor.png", col)


def tile_checker():
    H = W = 512
    y, x = np.mgrid[0:H, 0:W]
    check = (((x // 64) + (y // 64)) % 2).astype(np.float32)
    red = np.array([176, 44, 38], np.float32)
    white = np.array([232, 228, 220], np.float32)
    col = white[None, None, :] * (1 - check[..., None]) + red[None, None, :] * check[..., None]
    n = value_noise(H, W, octaves=4)
    col += (n[..., None] - 0.5) * 10
    for v in (x / W, y / H):
        d = np.minimum((v * 8) % 1.0, 1 - (v * 8) % 1.0)
        col -= np.clip(1 - d / 0.02, 0, 1)[..., None] * 26
    save("tile_checker.png", col)


def tile_small():
    H = W = 512
    base = np.array([228, 231, 232], np.float32)
    n = value_noise(H, W, octaves=4)
    col = base[None, None, :] + (n[..., None] - 0.5) * 8
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)
    for v in (x / W, y / H):
        d = np.minimum((v * 8) % 1.0, 1 - (v * 8) % 1.0)               # 8x8 tiles
        col -= np.clip(1 - d / 0.028, 0, 1)[..., None] * np.array([50, 48, 44], np.float32)
    save("tile_small.png", col)


def _awning(name, rgb_a, rgb_b):
    H = W = 512
    x = np.mgrid[0:H, 0:W][1].astype(np.float32)
    stripe = ((x / W * 8).astype(int) % 2).astype(np.float32)
    a = np.array(rgb_a, np.float32); b = np.array(rgb_b, np.float32)
    col = a[None, None, :] * (1 - stripe[..., None]) + b[None, None, :] * stripe[..., None]
    n = value_noise(H, W, octaves=4)
    col += (n[..., None] - 0.5) * 14                                   # canvas weave
    save(name, col)


def awnings():
    _awning("awning_red.png", (188, 52, 48), (238, 232, 222))
    _awning("awning_green.png", (36, 96, 66), (236, 230, 214))


def products():
    """Supermarket gondola front: 4 shelf rows of packed colorful boxes."""
    H = W = 512
    col = np.full((H, W, 3), 38, np.float32)                           # dark shelf gap
    palette = np.array([[196, 60, 50], [230, 168, 40], [60, 130, 190],
                        [86, 160, 70], [150, 70, 150], [230, 220, 200],
                        [40, 90, 150], [210, 120, 60]], np.float32)
    rows = 4
    for r in range(rows):
        y0 = int(H * r / rows) + 6
        y1 = int(H * (r + 1) / rows) - 14                              # shelf lip below
        x = 0
        while x < W - 4:
            w = int(RNG.integers(28, 64))
            c = palette[RNG.integers(0, len(palette))]
            jitter = RNG.normal(0, 8, 3).astype(np.float32)
            col[y0:y1, x:min(x + w - 3, W)] = c + jitter
            # simple label band
            band0 = y0 + (y1 - y0) // 3
            col[band0:band0 + 8, x + 3:min(x + w - 6, W)] = np.float32(235)
            x += w
        col[y1:y1 + 8, :] = np.float32(120)                            # steel shelf lip
    n = value_noise(H, W, octaves=3)
    col += (n[..., None] - 0.5) * 8
    save("products.png", col)


def menu_board():
    H, W = 256, 512
    col = np.full((H, W, 3), 24, np.float32)
    col[:, :] += (value_noise(H, W, 3)[..., None] - 0.5) * 6
    for r in range(5):                                                 # menu item lines
        y0 = 30 + r * 42
        col[y0:y0 + 10, 24:int(W * 0.55)] = np.float32(215)
        col[y0:y0 + 10, int(W * 0.8):W - 24] = np.array([250, 205, 90], np.float32)
    col[8:16, 24:W - 24] = np.array([250, 205, 90], np.float32)        # header rule
    save("menu_board.png", col)


def facade():
    """Window-grid building face: 4x4 windows per tile, spandrel between."""
    H = W = 512
    base = np.array([126, 118, 108], np.float32)                       # masonry
    n = value_noise(H, W, octaves=5)
    col = base[None, None, :] + (n[..., None] - 0.5) * 16
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)
    wx = (x / W * 4) % 1.0
    wy = (y / H * 4) % 1.0
    win = (wx > 0.18) & (wx < 0.82) & (wy > 0.22) & (wy < 0.78)
    glass = np.array([52, 66, 84], np.float32)
    sky = (value_noise(H, W, 3)[..., None]) * np.array([60, 66, 70], np.float32)
    lit = (RNG.random((4, 4)) > 0.72)                                  # a few lit rooms
    cell = (np.minimum((y / H * 4).astype(int), 3), np.minimum((x / W * 4).astype(int), 3))
    warm = lit[cell][..., None] * np.array([120, 90, 30], np.float32)
    col = np.where(win[..., None], glass[None, None, :] + sky + warm, col)
    sill = (wy > 0.78) & (wy < 0.84)
    col = np.where(sill[..., None], col - 30, col)
    save("facade.png", col)


def storefront():
    """Ground-floor shop front: tall glass panes, dark mullions, warm interior."""
    H = W = 512
    col = np.zeros((H, W, 3), np.float32)
    glass = np.array([46, 58, 66], np.float32)
    col[:, :] = glass
    n = value_noise(H, W, 4)
    col += (n[..., None]) * np.array([35, 35, 30], np.float32)         # reflections
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)
    warm = np.exp(-((y / H - 0.62) ** 2) / 0.05)[..., None] * np.array([70, 52, 22], np.float32)
    col += warm                                                        # interior glow
    mull = np.minimum((x / W * 3) % 1.0, 1 - (x / W * 3) % 1.0) < 0.02
    col = np.where(mull[..., None], np.float32(20), col)
    col[:26, :] = np.float32(30)                                       # header
    col[-20:, :] = np.float32(35)                                      # base kick
    save("storefront.png", col)


def curtainwall():
    """Modern glass office curtain wall: horizontal blue-glass bands + spandrels."""
    H = W = 512
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)
    glass = np.array([56, 84, 104], np.float32)
    spandrel = np.array([38, 46, 54], np.float32)
    band = (y / H * 10) % 1.0
    is_glass = band > 0.28
    col = np.where(is_glass[..., None], glass[None, None, :], spandrel[None, None, :])
    # sky reflection gradient + a few lit floors
    refl = (value_noise(H, W, 4)[..., None]) * np.array([40, 46, 52], np.float32)
    col = col + np.where(is_glass[..., None], refl, 0)
    lit = (RNG.random((10, 8)) > 0.8)
    cell = (np.minimum((y / H * 10).astype(int), 9), np.minimum((x / W * 8).astype(int), 7))
    col += (lit[cell] & is_glass)[..., None] * np.array([90, 80, 40], np.float32)
    mull = np.minimum((x / W * 8) % 1.0, 1 - (x / W * 8) % 1.0) < 0.04
    col = np.where(mull[..., None], np.float32(30), col)
    save("curtainwall.png", col)


def brownstone():
    """Brownstone / limestone row-house facade: warm stone + tall windows."""
    H = W = 512
    base = np.array([132, 96, 74], np.float32)
    n = value_noise(H, W, octaves=6)
    col = base[None, None, :] + (n[..., None] - 0.5) * 20
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)
    wx = (x / W * 3) % 1.0; wy = (y / H * 3) % 1.0
    win = (wx > 0.22) & (wx < 0.78) & (wy > 0.16) & (wy < 0.82)
    glass = np.array([40, 44, 50], np.float32)
    warm = (RNG.random((3, 3)) > 0.6)
    cell = (np.minimum((y / H * 3).astype(int), 2), np.minimum((x / W * 3).astype(int), 2))
    lit = warm[cell][..., None] * np.array([110, 84, 34], np.float32)
    col = np.where(win[..., None], glass[None, None, :] + lit, col)
    # stone course lines
    course = ((y / H * 24) % 1.0 < 0.04)
    col -= course[..., None] * 18
    save("brownstone.png", col)


def artdeco():
    """Art-deco skyscraper skin: pale stone vertical piers + recessed window strips."""
    H = W = 512
    stone = np.array([176, 170, 156], np.float32)
    dark = np.array([54, 52, 50], np.float32)
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)
    pier = (x / W * 12) % 1.0
    is_win = (pier > 0.32) & (pier < 0.68)                 # recessed window column
    col = np.where(is_win[..., None], dark[None, None, :], stone[None, None, :])
    n = value_noise(H, W, 5)
    col += (n[..., None] - 0.5) * 14
    # horizontal spandrel every floor inside the window columns
    floor = (y / H * 20) % 1.0
    span = is_win & (floor < 0.25)
    col = np.where(span[..., None], stone[None, None, :] * 0.7, col)
    lit = (RNG.random((20, 12)) > 0.82)
    cell = (np.minimum((y / H * 20).astype(int), 19), np.minimum((x / W * 12).astype(int), 11))
    col += (lit[cell] & is_win)[..., None] * np.array([120, 96, 44], np.float32)
    save("artdeco.png", col)


def tablecloth():
    H = W = 512
    base = np.array([238, 233, 222], np.float32)
    n = value_noise(H, W, octaves=6)
    col = base[None, None, :] + (n[..., None] - 0.5) * 8
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)
    weave = (np.sin(x / W * 2 * np.pi * 90) + np.sin(y / H * 2 * np.pi * 90)) * 1.6
    col += weave[..., None]
    save("tablecloth.png", col)


def water():
    H = W = 512
    base = np.array([48, 140, 180], np.float32)
    n1 = value_noise(H, W, octaves=5)
    n2 = value_noise(H, W, octaves=4)
    col = base[None, None, :] + (n1[..., None] - 0.5) * 30
    caustic = np.clip(1 - np.abs(n2 - 0.55) / 0.06, 0, 1)
    col += caustic[..., None] * np.array([70, 85, 90], np.float32)
    save("water.png", col)


def crosswalk():
    H = W = 512
    base = np.array([58, 58, 61], np.float32)
    n = value_noise(H, W, octaves=6)
    col = base[None, None, :] + (n[..., None] - 0.5) * 16
    x = np.mgrid[0:H, 0:W][1].astype(np.float32)
    stripe = ((x / W * 8).astype(int) % 2).astype(np.float32)
    paint = np.array([200, 200, 196], np.float32)
    wear = value_noise(H, W, 4)
    col = col * (1 - stripe[..., None] * 0.9) + \
        (paint[None, None, :] - wear[..., None] * 60) * stripe[..., None] * 0.9
    save("crosswalk.png", col)


