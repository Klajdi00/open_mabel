#!/usr/bin/env python3
"""
gen_home_objects.py -- wire the downloaded Google-Scanned-Objects meshes into a
single MuJoCo include used by scenes/mabel_home.xml.

Each object in assets/objects/<NAME>/ provides a textured visual mesh (model.obj
+ texture.png). We emit, per object, a namespaced <asset> block and a free-floating
<body> (freejoint) placed on a surface, with a convex-hull collision (MuJoCo
convexifies mesh collisions automatically). Paths are written relative to scenes/
(the top-level scene dir), so the include is valid when loaded via mabel_home.xml.

Re-run from the repo root after adding/moving objects:
    python scripts/tools/gen_home_objects.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "scenes", "home_objects.xml")

# (object dir, short prefix, x, y, z, yaw-deg, mass-kg) -- z is the resting base height.
# island top = 0.75 (objects ~0.76), kitchen counter top = 0.90 (objects ~0.91).
PLACEMENTS = [
    ("ACE_Coffee_Mug_Kristen_16_oz_cup",                "mug_red",   0.60,  0.25, 0.76,   0, 0.30),
    ("Cole_Hardware_Mug_Classic_Blue",                  "mug_blue",  0.60, -0.25, 0.76,  35, 0.30),
    ("Room_Essentials_Bowl_Turquiose",                  "bowl",      0.80,  0.02, 0.76,   0, 0.25),
    ("Threshold_Bistro_Ceramic_Dinner_Plate_Ruby_Ring", "plate",    0.90,  0.34, 0.76,   0, 0.35),
    ("Vans_Cereal_Honey_Nut_Crunch_11_oz_box",          "cereal",   0.84, -0.44, 0.76,  18, 0.40),
    ("Threshold_Porcelain_Pitcher_White",               "pitcher",  2.55, -0.35, 0.91,   0, 0.50),
    ("Threshold_Porcelain_Teapot_White",                "teapot",   2.55,  0.20, 0.91,   0, 0.50),
]

ASSET, BODY = [], []
for d, pfx, x, y, z, yaw, mass in PLACEMENTS:
    odir = os.path.join(ROOT, "assets", "objects", d)
    if not (os.path.exists(os.path.join(odir, "model.obj"))
            and os.path.exists(os.path.join(odir, "texture.png"))):
        print("  skip (missing files):", d); continue
    rel = f"../assets/objects/{d}"
    ASSET.append(
        f'    <texture type="2d" name="{pfx}_tex" file="{rel}/texture.png"/>\n'
        f'    <material name="{pfx}_mat" texture="{pfx}_tex" specular="0.3" shininess="0.4"/>\n'
        # explicit scale: mabel_full.xml sets a GLOBAL <mesh scale="0.001"> default
        # (its own STLs are in mm); these OBJs are in meters already.
        f'    <mesh name="{pfx}_mesh" file="{rel}/model.obj" scale="1 1 1"/>')
    BODY.append(
        f'    <body name="{pfx}" pos="{x} {y} {z}" euler="0 0 {yaw*3.14159265/180:.4f}">\n'
        f'      <freejoint name="{pfx}_joint"/>\n'
        f'      <geom type="mesh" mesh="{pfx}_mesh" material="{pfx}_mat" '
        f'contype="0" conaffinity="0" group="2" mass="0"/>\n'
        f'      <geom type="mesh" mesh="{pfx}_mesh" group="3" rgba="0.6 0.6 0.6 0" '
        f'condim="4" friction="1 0.05 0.001" mass="{mass}" '
        f'priority="1" solref="0.004 1" solimp="0.99 0.999 0.001"/>\n'
        f'    </body>')

xml = ('<mujoco model="home_objects">\n'
       '  <!-- AUTO-GENERATED by scripts/tools/gen_home_objects.py -- do not edit by hand.\n'
       '       Real Google-Scanned-Objects meshes (CC-BY 4.0). Included by mabel_home.xml. -->\n'
       '  <asset>\n' + "\n".join(ASSET) + "\n  </asset>\n\n"
       '  <worldbody>\n' + "\n".join(BODY) + "\n  </worldbody>\n</mujoco>\n")

with open(OUT, "w") as f:
    f.write(xml)
print(f"wrote {OUT}  ({len(BODY)} objects)")
