"""
scenegen -- programmatic builder for the extended MABEL scene library.

The nine original scenes (home, kitchen_fk, living_room, bedroom, office,
factory, assembly_line, warehouse, outdoor) are hand-authored XML; everything
added on top of them (supermarket, restaurants, cafes, gym, washroom, extra
living rooms, the one-floor full house, golf, front yard, rooftop lounge,
airport, and the dynamic city streets) is generated by this package so the
whole set stays consistent and regenerable:

    python3 scripts/tools/gen_extra_scenes.py         # from the repo root

Per scene it writes
    scenes/mabel_<name>.xml            the MJCF environment (robot included)
    scenes/mabel_<name>.dynamics.json  OPTIONAL sidecar: scripted actors
                                       (walking people, driving cars, moving
                                       conveyor belts) executed at runtime by
                                       simulation_bridge/dynamics.py
and rewrites scenes/scenes.json (the categorized registry the control-center
scene picker reads).

Conventions shared with the hand-authored scenes:
  * `<include file="../models/mabel_full.xml"/>` — robot at the origin, which
    must stay clear (~1.2 m) for spawn;
  * a plane geom named "floor"; room walls named "wall_*" (the thumbnail
    renderer's dollhouse cutaway keys on that prefix);
  * teleop mocap targets target_l / target_r / gaze_point in every scene;
  * textures from assets/textures (gen_home_textures.py, gen_env_textures.py,
    gen_env_textures2.py).

Dynamic actors are FREE-JOINTED, GRAVITY-COMPENSATED bodies (never mocap):
their pose lives in qpos, so the state memmap, cameras, web viewer and rig
mirror all see the motion without any new plumbing. Limbs/wheels are hinge
joints written kinematically by the bridge at keyframe rate.
"""
from .core import Scene, generate_registry
from . import (scenes_home, scenes_food, scenes_outdoor, scenes_city,
               scenes_industrial, scenes_la)


def generate_all():
    scenes = []
    for mod in (scenes_home, scenes_food, scenes_outdoor, scenes_city,
                scenes_industrial, scenes_la):
        scenes += mod.build_all()
    for s in scenes:
        s.write()
    generate_registry(scenes)
    return scenes
