"""scenes_industrial.py -- dynamics retrofit for the hand-authored assembly
line: the belt CARRIES its parts (slide-loop conveyor + part recycling) and a
line worker paces the far side tending stations A-C.

The scene XML itself stays hand-authored (mabel_assembly_line.xml, which
includes the generated assembly_actors.xml for the worker body); this module
only regenerates the include + the dynamics sidecar.

Belt mechanics: the belt geom lives on a slide joint driven kinematically at
the belt speed and snapped back by exactly one texture period (belt length /
texrepeat = 9.8 m / 14 = 0.70 m) so the wrap is visually seamless. Real
friction carries the parts; when a part reaches the +X end it respawns at the
-X end of the belt (deterministic loop).
"""
import json
import os

from .core import SCENES_DIR
from . import actors as A

BELT_SPEED = 0.22          # m/s, typical light assembly line
BELT_WRAP = 0.70           # slide wrap period = belt length / texrepeat
BELT_PARTS = ["as_tape1_joint", "as_screwdr_joint", "as_spk_joint",
              "as_tape2_joint"]


class _Include:
    """Tiny Scene stand-in for actor prefabs inside an include file."""

    def __init__(self):
        self._bodies = []
        self._mats = set()
        self.dyn = {"version": 1, "actors": [], "conveyors": []}

    def raw(self, xml, *mats):
        self._bodies.append(xml)
        self._mats.update(mats)

    def actor(self, spec):
        self.dyn["actors"].append(spec)

    def conveyor(self, spec):
        self.dyn["conveyors"].append(spec)


def build_all():
    inc = _Include()
    # line worker: paces the corridor between the belt and stations A-C,
    # dwelling at each station on a staggered cycle (ping-pong path).
    A.walker(inc, "worker", [[-3.0, 2.52], [3.0, 2.52]], closed=False,
             speed=0.85, s0=1.5, palette=6,
             stops=[{"s": 0.15, "period": 36.0, "dur": 7.0, "offset": 4.0},
                    {"s": 3.0, "period": 36.0, "dur": 7.0, "offset": 16.0},
                    {"s": 5.85, "period": 36.0, "dur": 7.0, "offset": 28.0}],
             comment="line worker tending stations A / B / C")
    xml = """<mujoco model="assembly_actors">
  <!-- AUTO-GENERATED by scripts/tools/scenegen (gen_extra_scenes.py) -- the
       assembly line's animated worker. Driven by simulation_bridge/dynamics.py
       via mabel_assembly_line.dynamics.json; a static mannequin otherwise. -->
  <worldbody>
%s
  </worldbody>
</mujoco>
""" % "\n".join(inc._bodies)
    path = os.path.join(SCENES_DIR, "assembly_actors.xml")
    with open(path, "w") as fp:
        fp.write(xml)
    print("wrote", path)

    inc.conveyor({
        "kind": "belt", "joint": "conv_belt_slide", "speed": BELT_SPEED,
        "wrap": BELT_WRAP,
        "recycle": {"joints": BELT_PARTS, "axis": 0, "max": 4.35,
                    "respawn": -4.35},
    })
    dyn_path = os.path.join(SCENES_DIR, "mabel_assembly_line.dynamics.json")
    with open(dyn_path, "w") as fp:
        json.dump(inc.dyn, fp, indent=1)
        fp.write("\n")
    print("wrote", dyn_path)
    return []              # no new registry entries; the scene already exists
